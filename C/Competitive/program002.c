#include<stdio.h>

/////////////////////////////////////////////////////////////////
//
//   Function Name : Display
//   Description   : Displays "Marvellous" five times
//   Date          : 21/08/2026
//   Author        : Shekhar Jalindar Nannaware
//
/////////////////////////////////////////////////////////////////

void Display()
{
    int i = 0;                         // Loop Counter

    for(i = 1; i <= 5; i++)
    {
        printf("Marvellous\n");
    }
}

/////////////////////////////////////////////////////////////////
//
//   Application to display "Marvellous" five times
//
/////////////////////////////////////////////////////////////////

int main()
{
    Display();

    return 0;
}

