#include<stdio.h>

/////////////////////////////////////////////////////////////////
//
//   Function Name : Display
//   Description   : Displays numbers from 5 to 5 using while loop
//   Date          : 21/08/2026
//   Author        : Shekhar Jalindar Nannaware
//
/////////////////////////////////////////////////////////////////

void Display()
{
    int i = 0;                         // Loop Counter

    i = 5;

    while(i <= 5)
    {
        printf("%d\n", i);
        i++;
    }
}

/////////////////////////////////////////////////////////////////
//
//   Application to display numbers from 5 to 5
//
/////////////////////////////////////////////////////////////////

int main()
{
    Display();

    return 0;
}

/////////////////////////////////////////////////////////////////
//
//   Output : 5
//
/////////////////////////////////////////////////////////////////